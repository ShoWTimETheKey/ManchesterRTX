// Collect every non-ASCII character used in the ManchesterRTX GUI sources into ManchesterGlyphs.h.
// RTXPT's ImGui backend builds a fixed font atlas from glyph ranges, so the Chinese text the GUI draws has to be listed up front
// (strings from Assets/manchester.app.json are added at runtime). Run before building: tools\node\node.exe tools\glyphs.mjs
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const dir = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'renderer', 'Rtxpt', 'Manchester');
const chars = new Set();
for (const f of fs.readdirSync(dir))
  if (/\.(cpp|h)$/.test(f) && f !== 'ManchesterGlyphs.h')
    for (const ch of fs.readFileSync(path.join(dir, f), 'utf8'))
      if (ch.codePointAt(0) > 0x7f && ch !== '﻿') chars.add(ch);
const text = [...chars].sort().join('');
const out = path.join(dir, 'ManchesterGlyphs.h');
const body = `// Generated by tools/glyphs.mjs from the ManchesterRTX GUI sources - do not edit.\n#pragma once\n\nstatic const char* const kManchesterGlyphText = "${text}";\n`;
if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== body) fs.writeFileSync(out, body);
console.log(`${chars.size} glyphs -> ${path.relative(process.cwd(), out)}`);
